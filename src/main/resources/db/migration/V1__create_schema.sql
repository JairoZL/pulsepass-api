CREATE TABLE venues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30)        NOT NULL,
    name VARCHAR(150)       NOT NULL,
    city VARCHAR(100)       NOT NULL,
    address   VARCHAR(255)  NOT NULL,
    capacity  INTEGER       NOT NULL,
    active    BOOLEAN       NOT NULL DEFAULT TRUE,

    CONSTRAINT uk_venues_code UNIQUE (code),
    CONSTRAINT ck_venues_capacity CHECK (capacity > 0));

CREATE TABLE users (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username  VARCHAR(50)  NOT NULL,
    email     VARCHAR(180) NOT NULL,
    active    BOOLEAN      NOT NULL DEFAULT TRUE,

    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE user_profiles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL,
    first_name  VARCHAR(80)  NOT NULL,
    last_name   VARCHAR(80)  NOT NULL,
    phone       VARCHAR(30),
    city        VARCHAR(100),
    birth_date  DATE         NOT NULL,

    CONSTRAINT fk_user_profiles_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_user_profiles_user UNIQUE (user_id)
);

CREATE TABLE artists (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_name  VARCHAR(80) NOT NULL,
    country     VARCHAR(80) NOT NULL,
    genre       VARCHAR(50) NOT NULL,
    active      BOOLEAN     NOT NULL DEFAULT TRUE,

    CONSTRAINT uk_artists_stage_name UNIQUE (stage_name)
);

CREATE TABLE events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY  PRIMARY KEY,
    event_code      VARCHAR(30)     NOT NULL,
    name            VARCHAR(80)     NOT NULL,
    description     VARCHAR(500)    NOT NULL,
    category        VARCHAR(100)    NOT NULL,
    status          VARCHAR(100)    NOT NULL,
    event_date      TIMESTAMP       NOT NULL,
    minimum_age     INTEGER         NOT NULL,
    venue_id        BIGINT          NOT NULL,

    CONSTRAINT uk_events_event_code     UNIQUE (event_code),
    CONSTRAINT fk_events_venue_id       FOREIGN KEY (venue_id) REFERENCES venues(id),
    CONSTRAINT ck_events_category       CHECK ( category IN('MUSIC','SPORTS','TECHNOLOGY',
                                                            'EDUCATION','CULTURE','ENTERTAINMENT')),
    CONSTRAINT ck_events_status         CHECK ( status IN('DRAFT','PUBLISHED', 'SOLD_OUT'
                                                        ,'CANCELLED', 'FINISHED') ),
    CONSTRAINT ck_events_minimum_age    CHECK ( minimum_age>=0)
    );

    CREATE TABLE event_artists (
        event_id    BIGINT NOT NULL,
        artist_id   BIGINT NOT NULL,

        CONSTRAINT pk_event_artists PRIMARY KEY (event_id,artist_id),
        CONSTRAINT fk_event_artists_event_id FOREIGN KEY (event_id) REFERENCES events(id),
        CONSTRAINT fk_event_artists_artist_id FOREIGN KEY (artist_id) REFERENCES artists(id)
    );

    CREATE TABLE tickets (
        id              BIGINT GENERATED BY DEFAULT AS IDENTITY  PRIMARY KEY,
        ticket_code     VARCHAR(30) NOT NULL,
        type            VARCHAR(30) NOT NULL,
        price           NUMERIC(10,2) NOT NULL ,
        status          VARCHAR(30) NOT NULL,
        purchase_date   TIMESTAMP NOT NULL,
        user_id         BIGINT NOT NULL,
        event_id        BIGINT NOT NULL,

        CONSTRAINT fk_tickets_user_id       FOREIGN KEY (user_id) REFERENCES users(id),
        CONSTRAINT fk_tickets_event_id      FOREIGN KEY (event_id) REFERENCES events(id),
        CONSTRAINT ck_tickets_type          CHECK (type IN ('GENERAL', 'VIP', 'BACKSTAGE', 'STUDENT') ),
        CONSTRAINT ck_tickets_status        CHECK (status IN ('RESERVED', 'PAID', 'CANCELLED', 'USED') ),
        CONSTRAINT ck_tickets_price         CHECK ( price>=0 ),
        CONSTRAINT uk_tickets_ticket_code   UNIQUE (ticket_code)
    );

    CREATE INDEX idx_tickets_user_id  ON tickets (user_id);
    CREATE INDEX idx_tickets_event_id ON tickets (event_id);
    CREATE INDEX idx_event_artists_artist_id ON event_artists (artist_id);
    CREATE INDEX idx_events_venue_id ON events (venue_id);

